#!/usr/bin/env python3
"""Generates one widget layout per (font, weight, height) combination.

Home-screen widgets (RemoteViews) cannot change a TextView's font, weight or
vertical stretch at runtime, so every combination is a static layout and the
app picks the right one. Size, colour, formats and visibility are set at
runtime. Run from the repo root:  python3 tools/gen_layouts.py
"""
import os

FONTS = [  # (resource, has opsz axis, min wght, max wght)
    ("inter", True, 100, 900),
    ("inter_tight", False, 100, 900),
    ("manrope", False, 200, 800),
    ("roboto_condensed", False, 100, 900),
    (None, False, 0, 0),  # phone's own system font
]
WEIGHTS = [100, 300, 400, 700, 900]
HEIGHTS = [100, 130, 160, 190, 220, 250]
SYSTEM = {100: ("sans-serif-thin", None), 300: ("sans-serif-light", None),
          400: ("sans-serif", None), 700: ("sans-serif", "bold"), 900: ("sans-serif-black", None)}

RES = "app/src/main/res/layout"
KT = "app/src/main/java/com/neonclock/widget/Layouts.kt"


def font_attrs(fi, weight):
    res, opsz, lo, hi = FONTS[fi]
    if res is None:
        fam, style = SYSTEM[weight]
        a = f'android:fontFamily="{fam}"'
        return a + (f' android:textStyle="{style}"' if style else "")
    w = max(lo, min(hi, weight))
    var = (f"'opsz' 32, 'wght' {w}" if opsz else f"'wght' {w}")
    return f'android:fontFamily="@font/{res}" android:fontVariationSettings="{var}"'


def date_attrs(fi):
    res, opsz, lo, hi = FONTS[fi]
    if res is None:
        return 'android:fontFamily="sans-serif-medium"'
    return f'android:fontFamily="@font/{res}" android:fontVariationSettings="\'wght\' 600"'


SHADOW = 'android:shadowColor="#4D000000" android:shadowDy="2" android:shadowRadius="12"'


def layout(fi, wi, hi):
    f = font_attrs(fi, WEIGHTS[wi])
    d = date_attrs(fi)
    sy = HEIGHTS[hi] / 100
    big = (f'{f} android:scaleY="{sy}" android:transformPivotY="0dp" '
           f'android:includeFontPadding="false" android:textColor="#B8FFFFFF" {SHADOW} '
           f'android:letterSpacing="-0.02"')
    small = f'{f} android:textColor="#B8FFFFFF" {SHADOW} android:includeFontPadding="false"'
    date = f'{d} android:textColor="#B8FFFFFF" {SHADOW} android:textSize="16sp" android:format12Hour="EEEE, d MMMM" android:format24Hour="EEEE, d MMMM"'
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_layouts.py. Do not edit by hand. -->
<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/widget_root"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:clipChildren="false"
    android:clipToPadding="false"
    android:gravity="center_horizontal"
    android:orientation="vertical"
    android:paddingTop="8dp">

    <TextClock android:id="@+id/date_top"
        android:layout_width="wrap_content" android:layout_height="wrap_content"
        android:layout_marginBottom="4dp" {date} />

    <LinearLayout android:id="@+id/inline_row"
        android:layout_width="wrap_content" android:layout_height="wrap_content"
        android:clipChildren="false" android:clipToPadding="false"
        android:orientation="horizontal">
        <TextClock android:id="@+id/time"
            android:layout_width="wrap_content" android:layout_height="wrap_content"
            android:textSize="120sp" android:format12Hour="h:mm" android:format24Hour="H:mm" {big} />
        <TextClock android:id="@+id/sec_inline"
            android:layout_width="wrap_content" android:layout_height="wrap_content"
            android:layout_marginStart="4dp" android:layout_marginTop="10dp"
            android:textSize="32sp" android:format12Hour="ss" android:format24Hour="ss" {small} />
    </LinearLayout>

    <TextClock android:id="@+id/hours"
        android:layout_width="wrap_content" android:layout_height="wrap_content"
        android:textSize="110sp" android:format12Hour="h" android:format24Hour="HH" {big} />
    <TextClock android:id="@+id/minutes"
        android:layout_width="wrap_content" android:layout_height="wrap_content"
        android:textSize="110sp" android:format12Hour="mm" android:format24Hour="mm" {big} />
    <TextClock android:id="@+id/sec_stack"
        android:layout_width="wrap_content" android:layout_height="wrap_content"
        android:textSize="32sp" android:format12Hour="ss" android:format24Hour="ss" {small} />

    <TextClock android:id="@+id/date_bottom"
        android:layout_width="wrap_content" android:layout_height="wrap_content"
        android:layout_marginTop="6dp" {date} />
</LinearLayout>
'''


def main():
    os.makedirs(RES, exist_ok=True)
    names = []
    for fi in range(len(FONTS)):
        for wi in range(len(WEIGHTS)):
            for hi in range(len(HEIGHTS)):
                n = f"clock_f{fi}_w{wi}_h{hi}"
                names.append(n)
                with open(f"{RES}/{n}.xml", "w") as fh:
                    fh.write(layout(fi, wi, hi))
    body = ",\n        ".join(f"R.layout.{n}" for n in names)
    with open(KT, "w") as fh:
        fh.write(f'''// Generated by tools/gen_layouts.py. Do not edit by hand.
package com.neonclock.widget

object Layouts {{
    const val FONTS = {len(FONTS)}
    const val WEIGHTS = {len(WEIGHTS)}
    const val HEIGHTS = {len(HEIGHTS)}
    val HEIGHT_PERCENT = intArrayOf({", ".join(map(str, HEIGHTS))})

    private val ids = intArrayOf(
        {body}
    )

    fun get(font: Int, weight: Int, height: Int): Int =
        ids[(font * WEIGHTS + weight) * HEIGHTS + height]
}}
''')
    print(f"{len(names)} layouts")


if __name__ == "__main__":
    main()
